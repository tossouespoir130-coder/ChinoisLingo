/**
 * Calcule et retourne le mot du jour de manière dynamique et déterministe.
 * Le mot change automatiquement toutes les 24 heures à minuit (heure locale).
 */
export function getDailyWord(date: Date = new Date()): WordOfTheDay {
  const year = date.getFullYear();
  const month = date.getMonth();
  const day = date.getDate();
  
  // Nombre de jours déterministe depuis l'époque pour rotation quotidienne exacte
  const dayIndex = Math.floor(new Date(year, month, day).getTime() / (1000 * 60 * 60 * 24));
  const safeIndex = Math.abs(dayIndex) % dailyWordsCatalog.length;
  
  return dailyWordsCatalog[safeIndex];
}
