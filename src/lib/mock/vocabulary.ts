/**
 * Normalizes strings by removing accents, tone marks, punctuation, and extra spaces.
 * Enables fuzzy matching: 'ni hao' will match 'nǐ hǎo', 'delai' will match 'délai'.
 */
export function normalizeSearchString(str: string): string {
  if (!str) return '';
  return str
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '') // remove diacritics / tone accents
    .replace(/[.,\/#!$%\^&\*;:{}=\-_`~()?'"‘’“”]/g, '')
    .trim();
}
